<?php
/**
 * UpturnStudio_Ai
 */
declare(strict_types=1);

namespace UpturnStudio\Ai;

use Magento\Framework\App\ObjectManager;
use RuntimeException;
use UpturnStudio\Ai\Api\AgentRunnerInterface;
use UpturnStudio\Ai\Api\AiManagerInterface;
use UpturnStudio\Ai\Api\Provider\ProviderInterface;
use UpturnStudio\Ai\Enums\Lab;
use UpturnStudio\Ai\Model\StandaloneFactory;

/**
 * Static access to the SDK, so agents read as they do in Laravel:
 *
 *     (new SalesCoach)->prompt('...', provider: [Ai::build(['driver' => 'anthropic', 'key' => $key])]);
 *
 * This is the only class that reaches for the ObjectManager, and only when nothing has been swapped in. Code that
 * prefers constructor injection can depend on AiManagerInterface and AgentRunnerInterface directly.
 */
class Ai
{
    /** @var AiManagerInterface|null */
    private static ?AiManagerInterface $manager = null;

    /** @var AgentRunnerInterface|null */
    private static ?AgentRunnerInterface $runner = null;

    /**
     * Create a provider at runtime, e.g. with a per-customer API key.
     *
     * @param array<string,mixed> $config Needs "driver"; takes "key", "url", "models", "headers" and "name".
     */
    public static function build(array $config): ProviderInterface
    {
        return self::manager()->build($config);
    }

    /**
     * A configured provider by name. Null means the default text provider.
     *
     * @param Lab|ProviderInterface|string|null $name
     */
    public static function provider(Lab|ProviderInterface|string|null $name = null): ProviderInterface
    {
        return self::manager()->provider($name);
    }

    /**
     * The provider manager.
     */
    public static function manager(): AiManagerInterface
    {
        if (self::$manager === null) {
            self::resolve();
        }

        return self::$manager;
    }

    /**
     * The agent runner.
     */
    public static function runner(): AgentRunnerInterface
    {
        if (self::$runner === null) {
            self::resolve();
        }

        return self::$runner;
    }

    /**
     * Replace the manager and runner, for tests or a custom wiring.
     *
     * @param AiManagerInterface $manager
     * @param AgentRunnerInterface $runner
     */
    public static function swap(AiManagerInterface $manager, AgentRunnerInterface $runner): void
    {
        self::$manager = $manager;
        self::$runner = $runner;
    }

    /**
     * Forget fakes, on-demand providers and any swapped instances. Call from a test's tearDown().
     */
    public static function reset(): void
    {
        self::$manager?->flushState();
        self::$manager = null;
        self::$runner = null;
    }

    /**
     * Create an object through the ObjectManager when there is one, so its dependencies are injected.
     *
     * @param class-string $class
     * @param array<int|string,mixed> $arguments Constructor arguments; named ones are matched by name.
     */
    public static function make(string $class, array $arguments = []): object
    {
        try {
            $objectManager = ObjectManager::getInstance();
        } catch (RuntimeException) {
            return new $class(...$arguments);
        }

        if ($arguments !== [] && array_is_list($arguments)) {
            return new $class(...$arguments);
        }

        return $objectManager->create($class, $arguments);
    }

    /**
     * Take the shared instances from the ObjectManager, or wire a standalone pair where Magento is not booted.
     */
    private static function resolve(): void
    {
        try {
            // phpcs:ignore Magento2.PHP.AutogeneratedClassNotInConstructor
            $objectManager = ObjectManager::getInstance();
            self::$manager = $objectManager->get(AiManagerInterface::class);
            self::$runner = $objectManager->get(AgentRunnerInterface::class);
        } catch (RuntimeException) {
            [self::$manager, self::$runner] = StandaloneFactory::create();
        }
    }
}
